module softmax #(
    // parameters
    parameter int NUM_INPUTS = 8,
    parameter int INPUT_WIDTH = 11,
    parameter int OUTPUT_WIDTH = 8
)(
    input logic clk,
    input logic rst_n,
    input logic [NUM_INPUTS*INPUT_WIDTH-1:0] inputs,
    input logic valid_in,
    output logic valid_out,
    output logic [NUM_INPUTS*OUTPUT_WIDTH-1:0] weights_flat
);

// unpack inputs
    logic signed [INPUT_WIDTH-1:0] scores [NUM_INPUTS-1:0];
    
    // internal pipeline signals
    logic signed [INPUT_WIDTH-1:0] max_val;
    logic signed [INPUT_WIDTH:0] shifted [NUM_INPUTS-1:0];
    logic [OUTPUT_WIDTH-1:0]       exp_val [NUM_INPUTS-1:0];
    logic [10:0] exp_sum;  // 11 bits: holds up to 8 × 255 = 2040
    logic [OUTPUT_WIDTH-1:0]       weights [NUM_INPUTS-1:0];

    localparam int LUT_SHIFT = 4;  // log2(16) — RTL divides by right-shifting

    // unpack flat input into array
    genvar i;
    generate
        for (i = 0; i < NUM_INPUTS; i++) begin
            assign scores[i] = inputs[INPUT_WIDTH*(i+1)-1 -: INPUT_WIDTH];
        end
    endgenerate

    // Stage 1 — find maximum score
always_comb begin
    max_val = scores[0];
    for (int j = 1; j < NUM_INPUTS; j++) begin
        if ($signed(scores[j]) > $signed(max_val))
            max_val = scores[j];
    end
end

always_comb begin
    for (int j = 0; j < NUM_INPUTS; j++) begin
        shifted[j] = (scores[j]) - (max_val);
    end
end

// Stage 3 — exp() LUT lookup
    // get_exp_val(n) = round(255 * exp(-n / 16)); body generated by
    // tb/gen_exp_lut.py — rerun that script if LUT_SHIFT changes.
    // default: covers both "genuinely decayed to zero" indices and any
    // index that falls outside this table entirely (out-of-range clamp).
    function automatic logic [OUTPUT_WIDTH-1:0] get_exp_val(input logic signed [INPUT_WIDTH:0] shift_val);
        logic signed [INPUT_WIDTH:0] idx;
        idx = (-shift_val) >>> LUT_SHIFT;
        case (idx)
            0: get_exp_val = 8'd255;
            1: get_exp_val = 8'd240;
            2: get_exp_val = 8'd225;
            3: get_exp_val = 8'd211;
