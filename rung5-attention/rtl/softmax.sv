            69: get_exp_val = 8'd3;
            70: get_exp_val = 8'd3;
            71: get_exp_val = 8'd3;
            72: get_exp_val = 8'd3;
            73: get_exp_val = 8'd3;
            74: get_exp_val = 8'd2;
            75: get_exp_val = 8'd2;
            76: get_exp_val = 8'd2;
            77: get_exp_val = 8'd2;
            78: get_exp_val = 8'd2;
            79: get_exp_val = 8'd2;
            80: get_exp_val = 8'd2;
            81: get_exp_val = 8'd2;
            82: get_exp_val = 8'd2;
            83: get_exp_val = 8'd1;
            84: get_exp_val = 8'd1;
            85: get_exp_val = 8'd1;
            86: get_exp_val = 8'd1;
            87: get_exp_val = 8'd1;
            88: get_exp_val = 8'd1;
            89: get_exp_val = 8'd1;
            90: get_exp_val = 8'd1;
            91: get_exp_val = 8'd1;
            92: get_exp_val = 8'd1;
            93: get_exp_val = 8'd1;
            94: get_exp_val = 8'd1;
