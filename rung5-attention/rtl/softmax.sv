            96: get_exp_val = 8'd1;
            97: get_exp_val = 8'd1;
            98: get_exp_val = 8'd1;
            99: get_exp_val = 8'd1;
            default: get_exp_val = 8'd0;
        endcase
    endfunction

always_comb begin
    for (int j = 0; j < NUM_INPUTS; j++) begin
        exp_val[j] = get_exp_val(shifted[j]);
    end
end

always_comb begin
    exp_sum = 0;
    for (int j = 0; j < NUM_INPUTS; j++) begin
        exp_sum += exp_val[j];
    end
end

function automatic logic [OUTPUT_WIDTH-1:0] get_weight(
    input logic [OUTPUT_WIDTH-1:0] exp_val_i,
    input logic [10:0] sum
);
    logic [15:0] raw;  // exp_val_i * 256 maxes at 255*256=65280, fits in 16 bits
    raw = (exp_val_i * 256) / sum;
    if(raw > 255) begin
        get_weight = 8'd255;
    end else begin
        get_weight = raw[7:0];
    end
endfunction

always_comb begin
    for (int j = 0; j < NUM_INPUTS; j++) begin
        weights[j] = get_weight(exp_val[j], exp_sum);
    end
end

always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        valid_out <= 0;
        weights_flat <= '0;
    end else begin
        valid_out <= valid_in;
        if (valid_in) begin
            for (int j = 0; j < NUM_INPUTS; j++) begin
                weights_flat[OUTPUT_WIDTH*(j+1)-1 -: OUTPUT_WIDTH] <= weights[j];
            end
        end
    end
end

endmodule